"use client";

import { useEffect, useId, useRef, useState } from "react";

type Props = {
  chart: string;
};

const MIN_ZOOM = 0.25;
const MAX_ZOOM = 3;

/** Natural width of a mermaid SVG, read from its viewBox. */
function svgWidth(svg: string): number | null {
  const match = svg.match(/viewBox="[\d.-]+ [\d.-]+ ([\d.]+) [\d.]+"/);
  return match ? Number(match[1]) : null;
}

/** Zoom level that fits the diagram into the viewport width (never upscales). */
function fitZoom(viewport: HTMLElement, naturalWidth: number): number {
  const available = viewport.clientWidth - 32; // minus p-4 padding
  return Math.min(1, Math.max(MIN_ZOOM, +(available / naturalWidth).toFixed(2)));
}

export function MermaidDiagram({ chart }: Props) {
  const id = useId().replace(/:/g, "");
  const [svg, setSvg] = useState<string>("");
  const [error, setError] = useState<string | null>(null);
  const [zoom, setZoom] = useState(1);
  const viewportRef = useRef<HTMLDivElement>(null);
  const naturalWidth = svg ? svgWidth(svg) : null;

  const fitToWidth = () => {
    const viewport = viewportRef.current;
    if (!viewport || !naturalWidth) return;
    setZoom(fitZoom(viewport, naturalWidth));
  };

  useEffect(() => {
    let cancelled = false;
    const media = window.matchMedia("(prefers-color-scheme: dark)");

    async function render() {
      try {
        // Loaded lazily: mermaid is large and only needed on this page.
        const { default: mermaid } = await import("mermaid");
        mermaid.initialize({
          startOnLoad: false,
          theme: media.matches ? "dark" : "default",
          er: { useMaxWidth: false },
          state: { useMaxWidth: false },
        });
        const result = await mermaid.render(`er-${id}`, chart);
        if (!cancelled) {
          setSvg(result.svg);
          setError(null);
          const width = svgWidth(result.svg);
          const viewport = viewportRef.current;
          if (width && viewport) {
            setZoom(fitZoom(viewport, width));
          }
        }
      } catch (err) {
        if (!cancelled) setError(err instanceof Error ? err.message : String(err));
      }
    }

    render();
    media.addEventListener("change", render);
    return () => {
      cancelled = true;
      media.removeEventListener("change", render);
    };
  }, [chart, id]);

  const changeZoom = (delta: number) =>
    setZoom((z) => Math.min(MAX_ZOOM, Math.max(MIN_ZOOM, +(z + delta).toFixed(2))));

  if (error) {
    return (
      <pre className="overflow-auto rounded-lg border border-red-300 bg-red-50 p-4 text-sm text-red-800 dark:border-red-800 dark:bg-red-950 dark:text-red-200">
        Mermaid syntax error:{"\n"}
        {error}
      </pre>
    );
  }

  return (
    <section className="rounded-xl border border-neutral-200 dark:border-neutral-800">
      <div className="flex items-center gap-2 border-b border-neutral-200 px-3 py-2 text-sm dark:border-neutral-800">
        <button
          type="button"
          onClick={() => changeZoom(-0.25)}
          className="rounded border border-neutral-300 px-2 py-0.5 hover:bg-neutral-100 dark:border-neutral-700 dark:hover:bg-neutral-800"
          aria-label="Zoom out"
        >
          −
        </button>
        <span className="w-12 text-center tabular-nums">{Math.round(zoom * 100)}%</span>
        <button
          type="button"
          onClick={() => changeZoom(0.25)}
          className="rounded border border-neutral-300 px-2 py-0.5 hover:bg-neutral-100 dark:border-neutral-700 dark:hover:bg-neutral-800"
          aria-label="Zoom in"
        >
          +
        </button>
        <button
          type="button"
          onClick={fitToWidth}
          className="ml-1 text-neutral-500 hover:underline"
        >
          Fit
        </button>
        <button
          type="button"
          onClick={() => setZoom(1)}
          className="text-neutral-500 hover:underline"
        >
          100%
        </button>
      </div>

      <div ref={viewportRef} className="max-h-[75vh] overflow-auto bg-white p-4 dark:bg-neutral-950">
        {svg ? (
          <div
            className="[&>svg]:h-auto [&>svg]:w-full [&>svg]:max-w-none"
            style={{ width: naturalWidth ? naturalWidth * zoom : undefined }}
            // SVG is generated by mermaid from our own repo file, not user input.
            dangerouslySetInnerHTML={{ __html: svg }}
          />
        ) : (
          <p className="text-neutral-500">Rendering diagram…</p>
        )}
      </div>
    </section>
  );
}
